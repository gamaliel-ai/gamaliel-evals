#!/usr/bin/env bun
/**
 * Generates eval/providers-matrix.yaml: one Gamaliel provider per (theology × profile).
 * Provider id format: Gamaliel:{theology}:{profile} for filtering in test cases.
 *
 * Run from repo root: bun run scripts/generate-providers-matrix.ts
 */
import * as fs from "fs";
import * as path from "path";

const EVAL_DIR = path.join(import.meta.dir, "..", "eval");
const THEOLOGIES_PATH = path.join(EVAL_DIR, "theologies.yaml");
const PROFILES_PATH = path.join(EVAL_DIR, "profiles.yaml");
const OUT_PATH = path.join(EVAL_DIR, "providers-matrix.yaml");

function loadYamlList(filePath: string): string[] {
  const raw = fs.readFileSync(filePath, "utf-8");
  const lines = raw.split("\n");
  const list: string[] = [];
  let inList = false;
  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith("#") || trimmed === "") continue;
    const dashMatch = line.match(/^\s+-\s+(.+)$/);
    if (dashMatch) {
      list.push(dashMatch[1].trim());
      inList = true;
    } else if (inList && line.match(/^\s+\w+:/)) break;
  }
  return list;
}

const theologies = loadYamlList(THEOLOGIES_PATH);
const profiles = loadYamlList(PROFILES_PATH);

const baseConfig = `
  provider: openai:chat:gpt-4o-mini
  config:
    apiBaseUrl: "https://api.gamaliel.ai/v1"
    passthrough:`;

const lines: string[] = [
  "# Generated by scripts/generate-providers-matrix.ts — do not edit by hand.",
  "# One provider per (theology × profile). Id format: Gamaliel:{theology}:{profile}.",
  "# Filter in test cases with providers: [Gamaliel:catholic:*, Gamaliel:anglican:*], etc.",
  "",
  "providers:",
];

for (const theology of theologies) {
  for (const profile of profiles) {
    const id = `Gamaliel:${theology}:${profile}`;
    lines.push(`  - id: ${id}`);
    lines.push(baseConfig);
    lines.push(`        theology: ${theology}`);
    lines.push(`        profile: ${profile}`);
    lines.push("");
  }
}

fs.writeFileSync(OUT_PATH, lines.join("\n").trimEnd() + "\n", "utf-8");
console.log(`Wrote ${OUT_PATH} (${theologies.length} × ${profiles.length} = ${theologies.length * profiles.length} providers)`);
